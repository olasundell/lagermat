import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const databaseUrl = process.env.SCOUTMAT_LOCAL_DATABASE_URL
  ?? "postgresql://postgres:postgres@127.0.0.1:54322/postgres";
const queryPath = resolve(root, "scripts/export-demo-fixture.sql");
const fixturePath = resolve(root, "supabase/fixtures/bjorkstad-v1.json");
const migrationPath = resolve(
  root,
  "supabase/migrations/20260730220001_canonical_demo_fixture_data.sql"
);
const checkOnly = process.argv.includes("--check");
const fromDatabase = process.argv.includes("--from-database");

if (checkOnly && fromDatabase) {
  throw new Error("--check and --from-database cannot be combined");
}

if (fromDatabase) {
  const exported = execFileSync("psql", [
    databaseUrl,
    "--no-psqlrc",
    "--quiet",
    "--tuples-only",
    "--no-align",
    "-f",
    queryPath
  ], {
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024
  }).trim();
  const definition = JSON.parse(exported);
  mkdirSync(dirname(fixturePath), { recursive: true });
  writeFileSync(fixturePath, `${JSON.stringify(definition, null, 2)}\n`, "utf8");
}

const source = readFileSync(fixturePath, "utf8");
const delimiter = "$lagermat_demo_fixture$";
if (source.includes(delimiter)) {
  throw new Error(`Fixture source cannot contain SQL delimiter ${delimiter}`);
}
const canonicalResult = execFileSync("psql", [
  databaseUrl,
  "--no-psqlrc",
  "--quiet",
  "--tuples-only",
  "--no-align",
  "-f",
  "-"
], {
  encoding: "utf8",
  input: `select (${delimiter}${source}${delimiter}::jsonb)::text;\n`,
  maxBuffer: 16 * 1024 * 1024
}).trim();
const canonical = canonicalResult;
const digest = createHash("sha256").update(canonical, "utf8").digest("hex");

const sql = `-- Generated by scripts/export-demo-fixture.mjs. Do not edit this payload by hand.
insert into app_private.demo_fixture_versions (
  fixture_key,
  template_version,
  content_digest,
  recipe_catalogue_digest,
  definition,
  is_active
) values (
  'bjorkstad',
  1,
  '${digest}',
  app_private.recipe_catalogue_digest(),
  $fixture$${canonical}$fixture$::jsonb,
  true
);
`;
if (checkOnly) {
  const installed = readFileSync(migrationPath, "utf8");
  if (installed !== sql) {
    throw new Error(
      "Canonical demo fixture migration is stale. Run node scripts/export-demo-fixture.mjs."
    );
  }
} else {
  writeFileSync(migrationPath, sql, "utf8");
}

process.stdout.write(
  `${fromDatabase ? "Wrote" : "Read"} ${fixturePath}\n`
    + `${checkOnly ? "Verified" : "Wrote"} ${migrationPath}\n`
    + `Fixture SHA-256: ${digest}\n`
);
